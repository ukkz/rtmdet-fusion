"""Keypoint dataset for RTMDet-Fusion

Reads the COCO-style annotations generated by tools/agora/extracter.py and converts the
head and body keypoints to unified coordinates relative to their reference bboxes.
"""

import json
import os
from pathlib import Path
from typing import Dict, List, Tuple

import cv2
import numpy as np
import torch
from torch.utils.data import Dataset
from pycocotools import mask as mask_utils

import sys
sys.path.insert(0, str(Path(__file__).parent.parent.parent))
from configs.default import (
    NUM_KEYPOINTS, IMG_SIZE,
    NUM_BODY_KEYPOINTS, BODY_KEYPOINT_SWAP_PAIRS, BODY_REF_BBOX_EXPAND,
)


class KeypointDataset(Dataset):
    """Person keypoint dataset (unified coordinates)

    Reads head (keypoints_cam) and body (keypoints_body_cam) keypoints and converts them to
    coordinates normalized by their reference bbox.

    Annotation fields used:
    {
        "bbox": [x, y, w, h],                 # person bbox
        "head_bbox": [x, y, w, h],            # head bbox (square)
        "keypoints_cam": [x0, y0, z0, v0, ..., x10, y10, z10, v10],  # 11 x 4 values
        "keypoints_body_cam": [...],          # 31 x 4 values, same layout
        "body_ignore": false,                 # exclude from the body losses
        "segmentation": RLE,                  # person mask (matching, mask teacher)
        "ignore": false,
        # with_mask_teachers only:
        "part_masks", "occlusion_mask", "occlusion_valid", "depth_file", "pelvis_depth"
    }
    keypoint layout:
        x = image x (pixels)
        y = pseudo-depth (reference point = 0, pixel-equivalent scale)
        z = H - image y (image Y flipped, up is positive)
        v = visibility (0 = out of frame, 1 = occluded, 2 = visible)

    Output (gt_keypoints_unified / gt_body_keypoints_unified), (N, K, 3) [rel_x, rel_y, rel_z]:
    - rel_x: (x - bbox.x1) / bbox.w
    - rel_y: y / ((bbox.w + bbox.h) / 2) + 0.5 (reference point = 0.5)
    - rel_z: (z - (H - bbox.y2)) / bbox.h (bbox bottom = 0, top = 1)
    No clamping: points outside the reference bbox keep values outside [0, 1].
    The head reference bbox is the annotated head_bbox; the body reference bbox is built
    from the 31 keypoints (see BODY_REF_BBOX_EXPAND).
    """

    def __init__(
        self,
        ann_file: str,
        img_dir: str,
        img_size: int = IMG_SIZE,
        num_keypoints: int = NUM_KEYPOINTS,
        is_train: bool = True,
        with_mask_teachers: bool = False
    ):
        """
        Args:
            with_mask_teachers: also return the part mask, occlusion and depth teachers
                                (needed to train the mask/depth branch; costs extra memory
                                and I/O for the RLEs and depth images)
        """
        self.img_dir = img_dir
        self.img_size = img_size
        self.num_keypoints = num_keypoints
        self.is_train = is_train
        self.with_mask_teachers = with_mask_teachers
        # Depth PNGs live under data/{split}/depth/... (img_dir = data/{split}/images)
        self.split_dir = Path(img_dir).parent

        # Load annotations
        with open(ann_file, 'r') as f:
            data = json.load(f)

        self.images = {img['id']: img for img in data['images']}

        # keypoints_cam is required (ignore=True annotations are kept and excluded after
        # matching). Only the fields used for training are kept: the training JSON is several
        # GB, and keeping unused fields exhausts RAM once DataLoader workers copy the dataset.
        _KEEP_KEYS = (
            'id', 'image_id', 'bbox', 'head_bbox', 'keypoints_cam',
            'segmentation', 'ignore',
            'keypoints_body_cam', 'body_ignore',
        )
        if with_mask_teachers:
            _KEEP_KEYS = _KEEP_KEYS + (
                'part_masks', 'occlusion_mask', 'occlusion_valid',
                'depth_file', 'pelvis_depth',
            )
        self.annotations = [
            {k: ann[k] for k in _KEEP_KEYS if k in ann}
            for ann in data['annotations']
            if 'keypoints_cam' in ann
        ]
        del data['annotations']

        # Convert numeric lists to float32 numpy arrays to cut the per-object overhead of
        # Python floats (several GB per process for ~870k annotations x ~170 values; avoids
        # ArrayMemoryError when workers copy the dataset)
        _ARRAY_KEYS = ('keypoints_cam', 'keypoints_body_cam', 'bbox', 'head_bbox')
        for ann in self.annotations:
            for k in _ARRAY_KEYS:
                if ann.get(k) is not None:
                    ann[k] = np.asarray(ann[k], dtype=np.float32)
            self._check_annotation(ann)

        ignored_count = sum(1 for ann in self.annotations if ann.get('ignore', False))

        # Group annotations by image (keeping the original order)
        self.img_to_anns = {}
        for ann in self.annotations:
            img_id = ann['image_id']
            if img_id not in self.img_to_anns:
                self.img_to_anns[img_id] = []
            self.img_to_anns[img_id].append(ann)

        # Images with at least one annotation
        self.image_ids = [
            img_id for img_id in self.images.keys()
            if img_id in self.img_to_anns and len(self.img_to_anns[img_id]) > 0
        ]

        print(f"Loaded {len(self.image_ids)} images with {len(self.annotations)} annotations (ignored: {ignored_count})")

    def _check_annotation(self, ann: dict) -> None:
        """Fail early on annotations without the head/body keypoint fields"""
        head = ann.get('keypoints_cam')
        body = ann.get('keypoints_body_cam')
        if (head is None or len(head) != self.num_keypoints * 4
                or body is None or len(body) != NUM_BODY_KEYPOINTS * 4):
            raise ValueError(
                f"Annotation {ann.get('id')} (image {ann.get('image_id')}) lacks the keypoint "
                f"fields: 'keypoints_cam' ({self.num_keypoints} x 4 values) and "
                f"'keypoints_body_cam' ({NUM_BODY_KEYPOINTS} x 4 values) are required. "
                f"Generate the data with tools/agora/extracter.py."
            )

    def __len__(self) -> int:
        return len(self.image_ids)

    def _decode_rle_mask(self, rle: dict, target_size: Tuple[int, int]) -> np.ndarray:
        """Decode an RLE mask and resize it

        Args:
            rle: RLE-encoded mask {'size': [h, w], 'counts': ...}
            target_size: output size (height, width)

        Returns:
            binary mask (target_h, target_w)
        """
        if rle is None:
            return None

        # Decode
        if isinstance(rle["counts"], str):
            rle_copy = {"size": rle["size"], "counts": rle["counts"].encode("utf-8")}
        else:
            rle_copy = rle.copy()

        mask = mask_utils.decode(rle_copy)

        # Resize if needed
        if mask.shape[:2] != target_size:
            mask = cv2.resize(mask, (target_size[1], target_size[0]), interpolation=cv2.INTER_NEAREST)

        return mask.astype(np.uint8)

    def _augment_image(
        self,
        img: np.ndarray,
        bboxes: np.ndarray,
        head_bboxes: np.ndarray,
        keypoints_cam: np.ndarray,
        visibilities: np.ndarray,
        img_h: int,
        body_keypoints_cam: np.ndarray = None,
        body_visibilities: np.ndarray = None,
    ) -> Tuple:
        """Data augmentation (training only)

        Args:
            img: image
            bboxes: person bbox (N, 4) [x1, y1, x2, y2]
            head_bboxes: head bbox (N, 4) [x1, y1, x2, y2]
            keypoints_cam: head keypoints (N, K, 3) [x, y, z]
            visibilities: visibility (N, K)
            img_h: image height
            body_keypoints_cam: body keypoints (N, 31, 3)
            body_visibilities: body visibility (N, 31)

        Returns:
            (img, bboxes, head_bboxes, keypoints_cam, visibilities,
             body_keypoints_cam, body_visibilities, is_flipped) after augmentation
        """
        is_flipped = False

        if not self.is_train:
            return (img, bboxes, head_bboxes, keypoints_cam, visibilities,
                    body_keypoints_cam, body_visibilities, is_flipped)

        h, w = img.shape[:2]

        # Horizontal flip (50%)
        if np.random.rand() < 0.5:
            is_flipped = True
            img = cv2.flip(img, 1)
            if len(bboxes) > 0:
                bboxes[:, [0, 2]] = w - bboxes[:, [2, 0]]
                head_bboxes[:, [0, 2]] = w - head_bboxes[:, [2, 0]]

                # Only x flips; the depth y and the height z are unchanged
                keypoints_cam[:, :, 0] = w - keypoints_cam[:, :, 0]

                # Swap the left/right keypoints
                # left_ear(2) <-> right_ear(3)
                # left_eye(4) <-> right_eye(5)
                keypoints_cam[:, [2, 3]] = keypoints_cam[:, [3, 2]]
                keypoints_cam[:, [4, 5]] = keypoints_cam[:, [5, 4]]
                visibilities[:, [2, 3]] = visibilities[:, [3, 2]]
                visibilities[:, [4, 5]] = visibilities[:, [5, 4]]

                # Body keypoints
                if body_keypoints_cam is not None:
                    body_keypoints_cam[:, :, 0] = w - body_keypoints_cam[:, :, 0]
                    for li, ri in BODY_KEYPOINT_SWAP_PAIRS:
                        body_keypoints_cam[:, [li, ri]] = body_keypoints_cam[:, [ri, li]]
                        body_visibilities[:, [li, ri]] = body_visibilities[:, [ri, li]]

        # Brightness / contrast
        if np.random.rand() < 0.5:
            alpha = np.random.uniform(0.8, 1.2)
            beta = np.random.uniform(-20, 20)
            img = np.clip(img * alpha + beta, 0, 255).astype(np.uint8)

        return (img, bboxes, head_bboxes, keypoints_cam, visibilities,
                body_keypoints_cam, body_visibilities, is_flipped)

    def _convert_to_normalized(
        self,
        keypoints_cam: np.ndarray,
        head_bboxes: np.ndarray,
        img_h: int
    ) -> np.ndarray:
        """Convert keypoints to coordinates normalized by a reference bbox (head and body)

        No clamping: keypoints outside the reference bbox keep out-of-range values; the
        training code handles them with the margin-bin range check and target_weight.

        Args:
            keypoints_cam: (N, K, 3) [x, y, z]
            head_bboxes: (N, 4) reference bbox [x1, y1, x2, y2]
            img_h: image height

        Returns:
            normalized: (N, K, 3) [rel_x, rel_y, rel_z] (not clamped)
        """
        N = keypoints_cam.shape[0]
        K = keypoints_cam.shape[1] if keypoints_cam.ndim == 3 else self.num_keypoints
        if N == 0:
            return np.zeros((0, K, 3), dtype=np.float32)

        # Reference bbox
        x1 = head_bboxes[:, 0:1]  # (N, 1)
        y1 = head_bboxes[:, 1:2]  # (N, 1)
        x2 = head_bboxes[:, 2:3]  # (N, 1)
        y2 = head_bboxes[:, 3:4]  # (N, 1)
        w = x2 - x1
        h = y2 - y1
        bbox_size = (w + h) / 2  # unit of the pseudo-depth (y)

        # Axes (N, K)
        cam_x = keypoints_cam[:, :, 0]  # image x
        cam_y = keypoints_cam[:, :, 1]  # depth (reference point = 0)
        cam_z = keypoints_cam[:, :, 2]  # H - image y

        # x is normalized by w and z by h, matching the decoding (rel_x * w, rel_z * h);
        # normalizing both by (w+h)/2 would distort rectangular (body) reference bboxes.
        # rel_x: (x - x1) / w
        rel_x = (cam_x - x1) / (w + 1e-8)

        # rel_y: y / bbox_size + 0.5 (reference point 0 -> 0.5)
        # The pseudo-depth unit is (w+h)/2, as in the decoding
        rel_y = cam_y / (bbox_size + 1e-8) + 0.5

        # rel_z: z is already H - y_img.
        # The bbox bottom is y1+h in image coordinates, i.e. H - (y1+h) in z, so
        # rel_z = (z - (H - y1 - h)) / h = (y1 + h - y_img) / h
        # (bottom of the reference bbox = 0, top = 1)
        bbox_bottom_cam = img_h - (y1 + h)  # z of the bbox bottom
        rel_z = (cam_z - bbox_bottom_cam) / (h + 1e-8)

        normalized = np.stack([rel_x, rel_y, rel_z], axis=-1)

        return normalized.astype(np.float32)

    # Channel order of the mask teachers (MaskDepthBranch outputs 0-6)
    MASK_CHANNEL_NAMES = ('clothed', 'body', 'head', 'torso', 'limbs', 'hands', 'occlusion')

    def _build_mask_teachers(
        self,
        anns: list,
        gt_masks: torch.Tensor,
        body_ref_bboxes: torch.Tensor,
        img_info: dict,
        is_flipped: bool,
        scale_y: float,
    ) -> Dict[str, torch.Tensor]:
        """Build the mask / depth teacher tensors (teacher resolution img_size/4)

        Channels: 0 = clothed full body (amodal), 1 = bare body (union of the parts),
        2-5 = parts, 6 = occlusion.
        Depth: rel_y equivalent (0.5 = pelvis, pseudo-depth normalized by the body
        reference bbox (w+h)/2).
        """
        sup = self.img_size // 4
        N = len(anns)
        teachers = np.zeros((N, 7, sup, sup), dtype=np.float32)
        ch_valid = np.zeros((N, 7), dtype=np.bool_)
        depth_t = np.full((N, sup, sup), 0.5, dtype=np.float32)
        depth_v = np.zeros((N, sup, sup), dtype=np.bool_)

        img_mirrored = bool(img_info.get('mirrored'))
        focal = float(img_info.get('focal_length', 0) or 0)

        for n, ann in enumerate(anns):
            # ch0: clothed full body (gt_masks are already flipped, img_size resolution)
            if ann.get('segmentation') is not None and n < len(gt_masks):
                teachers[n, 0] = cv2.resize(
                    gt_masks[n].numpy(), (sup, sup), interpolation=cv2.INTER_NEAREST
                )
                ch_valid[n, 0] = True

            # ch2-5: bare-body parts (RLE at teacher resolution; mirrored crops are
            # already mirrored in the JSON)
            pm = ann.get('part_masks')
            if pm is not None:
                for j, name in enumerate(('head', 'torso', 'limbs', 'hands')):
                    rle = pm.get(name)
                    if rle is not None:
                        mk = self._decode_rle_mask(rle, (sup, sup))
                        if is_flipped:
                            mk = cv2.flip(mk, 1)
                        teachers[n, 2 + j] = mk
                # ch1: bare body = union of the parts
                teachers[n, 1] = teachers[n, 2:6].max(axis=0)
                ch_valid[n, 1:6] = True

            # ch6: occlusion (RLE at crop resolution; a None RLE means "no occlusion",
            # i.e. a valid all-zero teacher)
            if ann.get('occlusion_valid'):
                occ = ann.get('occlusion_mask')
                if occ is not None:
                    mk = self._decode_rle_mask(occ, (sup, sup))
                    if is_flipped:
                        mk = cv2.flip(mk, 1)
                    teachers[n, 6] = mk
                ch_valid[n, 6] = True

            # Depth (uint16 mm PNG -> rel_y equivalent)
            depth_file = ann.get('depth_file')
            pelvis = ann.get('pelvis_depth')
            if (depth_file and pelvis and pelvis > 0 and focal > 0
                    and not ann.get('body_ignore', False)):
                dpath = self.split_dir / depth_file
                raw = cv2.imread(str(dpath), cv2.IMREAD_UNCHANGED)
                if raw is not None:
                    if img_mirrored:
                        raw = cv2.flip(raw, 1)
                    if is_flipped:
                        raw = cv2.flip(raw, 1)
                    raw = cv2.resize(raw, (sup, sup), interpolation=cv2.INTER_NEAREST)
                    valid = raw > 0
                    if valid.any():
                        bx1, by1, bx2, by2 = body_ref_bboxes[n].tolist()
                        body_size = ((bx2 - bx1) + (by2 - by1)) / 2
                        if body_size > 1:
                            z = raw[valid].astype(np.float32) / 1000.0
                            # pseudo-depth (crop px) -> img_size scale -> bbox-normalized (rel_y)
                            pseudo = (z - pelvis) * focal / pelvis * scale_y
                            depth_t[n][valid] = pseudo / body_size + 0.5
                            depth_v[n] = valid

        return {
            'gt_mask_teachers': torch.from_numpy(teachers),
            'gt_mask_channel_valid': torch.from_numpy(ch_valid),
            'gt_depth_teachers': torch.from_numpy(depth_t),
            'gt_depth_valid': torch.from_numpy(depth_v),
        }

    def __getitem__(self, idx: int) -> Dict:
        img_id = self.image_ids[idx]
        img_info = self.images[img_id]
        anns = self.img_to_anns.get(img_id, [])

        # Load the image
        img_path = os.path.join(self.img_dir, img_info['file_name'])
        img = cv2.imread(img_path)
        if img is None:
            raise FileNotFoundError(f"Image not found: {img_path}")

        orig_h, orig_w = img.shape[:2]

        # Gather annotations
        bboxes = []
        head_bboxes = []
        keypoints_cam = []
        visibilities = []
        segmentation_rles = []  # GT masks (RLE)
        ignore_flags = []
        body_keypoints_cam = []
        body_visibilities = []
        body_ignore_flags = []

        for ann in anns:
            # Person bbox [x, y, w, h] -> [x1, y1, x2, y2]
            x, y, w, h = ann['bbox']
            bboxes.append([x, y, x + w, y + h])

            # Head bbox [x, y, w, h] -> [x1, y1, x2, y2]
            hx, hy, hw, hh = ann['head_bbox']
            head_bboxes.append([hx, hy, hx + hw, hy + hh])

            # Head keypoints (11 x 4: x, y, z, v)
            kpts_cam_raw = ann['keypoints_cam']
            kpts_cam = []
            vis = []
            for i in range(self.num_keypoints):
                kpts_cam.append([
                    kpts_cam_raw[i * 4],
                    kpts_cam_raw[i * 4 + 1],
                    kpts_cam_raw[i * 4 + 2],
                ])
                vis.append(float(kpts_cam_raw[i * 4 + 3]))

            keypoints_cam.append(kpts_cam)
            visibilities.append(vis)

            # Segmentation mask (RLE)
            segmentation_rles.append(ann.get('segmentation', None))

            ignore_flags.append(ann.get('ignore', False))

            # Body keypoints (31 x 4: x, y, z, v)
            body_cam_raw = ann['keypoints_body_cam']
            b_kpts = []
            b_vis = []
            for i in range(NUM_BODY_KEYPOINTS):
                b_kpts.append([
                    body_cam_raw[i * 4],
                    body_cam_raw[i * 4 + 1],
                    body_cam_raw[i * 4 + 2],
                ])
                b_vis.append(float(body_cam_raw[i * 4 + 3]))
            body_keypoints_cam.append(b_kpts)
            body_visibilities.append(b_vis)
            body_ignore_flags.append(bool(ann.get('body_ignore', False)))

        bboxes = np.array(bboxes, dtype=np.float32) if bboxes else np.zeros((0, 4), dtype=np.float32)
        head_bboxes = np.array(head_bboxes, dtype=np.float32) if head_bboxes else np.zeros((0, 4), dtype=np.float32)
        keypoints_cam = np.array(keypoints_cam, dtype=np.float32) if keypoints_cam else np.zeros((0, self.num_keypoints, 3), dtype=np.float32)
        visibilities = np.array(visibilities, dtype=np.float32) if visibilities else np.zeros((0, self.num_keypoints), dtype=np.float32)
        ignore_flags = np.array(ignore_flags, dtype=np.bool_) if ignore_flags else np.zeros((0,), dtype=np.bool_)
        body_keypoints_cam = np.array(body_keypoints_cam, dtype=np.float32) if body_keypoints_cam else np.zeros((0, NUM_BODY_KEYPOINTS, 3), dtype=np.float32)
        body_visibilities = np.array(body_visibilities, dtype=np.float32) if body_visibilities else np.zeros((0, NUM_BODY_KEYPOINTS), dtype=np.float32)
        body_ignore_flags = np.array(body_ignore_flags, dtype=np.bool_) if body_ignore_flags else np.zeros((0,), dtype=np.bool_)

        # Augmentation
        (img, bboxes, head_bboxes, keypoints_cam, visibilities,
         body_keypoints_cam, body_visibilities, is_flipped) = self._augment_image(
            img, bboxes, head_bboxes, keypoints_cam, visibilities, orig_h,
            body_keypoints_cam=body_keypoints_cam,
            body_visibilities=body_visibilities,
        )

        # Resize
        img = cv2.resize(img, (self.img_size, self.img_size))
        scale_x = self.img_size / orig_w
        scale_y = self.img_size / orig_h

        if len(bboxes) > 0:
            bboxes[:, [0, 2]] *= scale_x
            bboxes[:, [1, 3]] *= scale_y
            head_bboxes[:, [0, 2]] *= scale_x
            head_bboxes[:, [1, 3]] *= scale_y
            # x scales with the width; z and the pixel-equivalent depth y with the height
            keypoints_cam[:, :, 0] *= scale_x  # x
            keypoints_cam[:, :, 1] *= scale_y  # y (depth)
            keypoints_cam[:, :, 2] *= scale_y  # z = H - y
            body_keypoints_cam[:, :, 0] *= scale_x
            body_keypoints_cam[:, :, 1] *= scale_y
            body_keypoints_cam[:, :, 2] *= scale_y

        # GT body reference bbox: bounding rectangle of the 31 keypoints x BODY_REF_BBOX_EXPAND
        # (not squared; a square box around a standing person makes nearly half of the grid
        # features background). The square body_ref_bbox stored in the annotations is not used.
        if body_keypoints_cam.shape[0] > 0:
            bkx = body_keypoints_cam[:, :, 0]                      # image x
            bky = self.img_size - body_keypoints_cam[:, :, 2]      # image y = H - z
            x_min = bkx.min(axis=1)
            x_max = bkx.max(axis=1)
            y_min = bky.min(axis=1)
            y_max = bky.max(axis=1)
            bcx = (x_min + x_max) / 2
            bcy = (y_min + y_max) / 2
            half_w = np.maximum((x_max - x_min) / 2 * BODY_REF_BBOX_EXPAND, 2.0)
            half_h = np.maximum((y_max - y_min) / 2 * BODY_REF_BBOX_EXPAND, 2.0)
            body_ref_bboxes = np.stack(
                [bcx - half_w, bcy - half_h, bcx + half_w, bcy + half_h], axis=1
            ).astype(np.float32)
        else:
            body_ref_bboxes = np.zeros((0, 4), dtype=np.float32)

        # Normalized coordinates (at the resized img_size, not clamped)
        keypoints_unified = self._convert_to_normalized(
            keypoints_cam, head_bboxes, self.img_size
        )
        body_keypoints_unified = self._convert_to_normalized(
            body_keypoints_cam, body_ref_bboxes, self.img_size
        )

        # To tensors
        if len(bboxes) > 0:
            bboxes = torch.tensor(bboxes, dtype=torch.float32)
            head_bboxes = torch.tensor(head_bboxes, dtype=torch.float32)
            keypoints_unified = torch.tensor(keypoints_unified, dtype=torch.float32)
            visibilities = torch.tensor(visibilities, dtype=torch.float32)
            ignore_flags = torch.tensor(ignore_flags, dtype=torch.bool)
            body_ref_bboxes = torch.tensor(body_ref_bboxes, dtype=torch.float32)
            body_keypoints_unified = torch.tensor(body_keypoints_unified, dtype=torch.float32)
            body_visibilities = torch.tensor(body_visibilities, dtype=torch.float32)
            body_ignore_flags = torch.tensor(body_ignore_flags, dtype=torch.bool)
        else:
            bboxes = torch.zeros((0, 4), dtype=torch.float32)
            head_bboxes = torch.zeros((0, 4), dtype=torch.float32)
            keypoints_unified = torch.zeros((0, self.num_keypoints, 3), dtype=torch.float32)
            visibilities = torch.zeros((0, self.num_keypoints), dtype=torch.float32)
            ignore_flags = torch.zeros((0,), dtype=torch.bool)
            body_ref_bboxes = torch.zeros((0, 4), dtype=torch.float32)
            body_keypoints_unified = torch.zeros((0, NUM_BODY_KEYPOINTS, 3), dtype=torch.float32)
            body_visibilities = torch.zeros((0, NUM_BODY_KEYPOINTS), dtype=torch.float32)
            body_ignore_flags = torch.zeros((0,), dtype=torch.bool)

        # Decode and resize the GT masks
        gt_masks = []
        target_size = (self.img_size, self.img_size)
        for rle in segmentation_rles:
            mask = self._decode_rle_mask(rle, target_size)
            if mask is not None:
                # Flip the mask together with the image
                if is_flipped:
                    mask = cv2.flip(mask, 1)
                gt_masks.append(mask)
            else:
                # Empty mask when there is none
                gt_masks.append(np.zeros(target_size, dtype=np.uint8))

        # Stack masks (N, H, W)
        if gt_masks:
            gt_masks = np.stack(gt_masks, axis=0)
            gt_masks = torch.from_numpy(gt_masks)
        else:
            gt_masks = torch.zeros((0, self.img_size, self.img_size), dtype=torch.uint8)

        # Mask / depth teachers (with_mask_teachers only)
        mask_teacher_tensors = None
        if self.with_mask_teachers:
            mask_teacher_tensors = self._build_mask_teachers(
                anns, gt_masks, body_ref_bboxes, img_info, is_flipped, scale_y
            )

        # Image normalization (ImageNet mean/std in BGR order, as the RTMDet preprocessor)
        mean = np.array([103.53, 116.28, 123.675], dtype=np.float32)
        std = np.array([57.375, 57.12, 58.395], dtype=np.float32)
        img_norm = (img.astype(np.float32) - mean) / std
        img_tensor = torch.from_numpy(img_norm.transpose(2, 0, 1))

        result = {
            'image': img_tensor,
            'gt_bboxes': bboxes,
            'gt_head_bboxes': head_bboxes,
            'gt_keypoints_unified': keypoints_unified,  # (N, K, 3) normalized coordinates
            'gt_visibilities': visibilities,
            'gt_masks': gt_masks,  # (N, H, W) GT segmentation masks
            'gt_ignore_flags': ignore_flags,  # (N,)
            'gt_body_ref_bboxes': body_ref_bboxes,  # (N, 4) body reference bbox
            'gt_body_keypoints_unified': body_keypoints_unified,  # (N, 31, 3)
            'gt_body_visibilities': body_visibilities,  # (N, 31)
            'gt_body_ignore_flags': body_ignore_flags,  # (N,)
            'image_id': img_id,
            'img_shape': (self.img_size, self.img_size),
        }
        if mask_teacher_tensors is not None:
            result.update(mask_teacher_tensors)
        return result


def collate_fn(batch: List[Dict]) -> Dict:
    """Batch collate function"""
    images = torch.stack([item['image'] for item in batch])
    gt_bboxes = [item['gt_bboxes'] for item in batch]
    gt_head_bboxes = [item['gt_head_bboxes'] for item in batch]
    gt_keypoints_unified = [item['gt_keypoints_unified'] for item in batch]
    gt_visibilities = [item['gt_visibilities'] for item in batch]
    gt_masks = [item['gt_masks'] for item in batch]  # for the Hungarian matching
    gt_ignore_flags = [item['gt_ignore_flags'] for item in batch]
    image_ids = [item['image_id'] for item in batch]
    img_shapes = [item['img_shape'] for item in batch]

    return {
        'images': images,
        'gt_bboxes': gt_bboxes,
        'gt_head_bboxes': gt_head_bboxes,
        'gt_keypoints_unified': gt_keypoints_unified,
        'gt_visibilities': gt_visibilities,
        'gt_masks': gt_masks,  # List[Tensor(N, H, W)]
        'gt_ignore_flags': gt_ignore_flags,  # List[Tensor(N,)]
        'gt_body_ref_bboxes': [item['gt_body_ref_bboxes'] for item in batch],
        'gt_body_keypoints_unified': [item['gt_body_keypoints_unified'] for item in batch],
        'gt_body_visibilities': [item['gt_body_visibilities'] for item in batch],
        'gt_body_ignore_flags': [item['gt_body_ignore_flags'] for item in batch],
        # Mask / depth teachers (present only with with_mask_teachers)
        'gt_mask_teachers': [item.get('gt_mask_teachers') for item in batch],
        'gt_mask_channel_valid': [item.get('gt_mask_channel_valid') for item in batch],
        'gt_depth_teachers': [item.get('gt_depth_teachers') for item in batch],
        'gt_depth_valid': [item.get('gt_depth_valid') for item in batch],
        'image_ids': image_ids,
        'img_shapes': img_shapes,
    }
